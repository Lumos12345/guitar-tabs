def tab_block(d, y, lines, size=20, x0=None, label=True, lhf=1.5):
    """Draw one 6-line tab block. Returns next y."""
    f = mono(size, True)
    cw = f.getlength("0")
    if x0 is None:
        x0 = M_TAB
    lh = int(size * lhf)
    n = 6
    top = y
    # string lines
    maxlen = max(len(l) for l in lines)
    tabw = maxlen * cw
    for i in range(n):
        yy = top + i * lh
        lw = 4 if i == n - 1 else 1
        col = LINEC if i < n - 1 else (110, 110, 118)
        d.line([x0, yy, x0 + tabw, yy], fill=col, width=lw)
    # overlay text
    for i, l in enumerate(lines):
        yy = top + i * lh
        for j, ch in enumerate(l):
            if ch == " " or ch == "-":
                continue
            col = INK
            if ch in "bhprv/^~><":
                col = (200, 60, 40)
            elif ch.isdigit():
                col = DARK
            elif ch in "eBGDAE" and j == 0:
                col = GRAY
            elif ch == "|":
                col = GRAY
            d.text((x0 + j * cw, yy), ch, font=f, fill=col, anchor="lm")
    return top + (n - 1) * lh + lh

