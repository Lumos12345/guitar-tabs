import os
from PIL import Image, ImageDraw, ImageFont

OUT = "/tmp/newbie"
os.makedirs(OUT, exist_ok=True)

W, H = 1654, 2339
DARK = (31, 58, 95)          # #1f3a5f
INK = (20, 20, 25)
GRAY = (130, 130, 138)
LINEC = (70, 70, 78)
LIGHT = (235, 238, 242)
YEL_BG = (255, 248, 225)
YEL_BR = (230, 168, 23)
RED_BG = (253, 236, 234)
RED_BR = (217, 83, 79)
WHITE = (255, 255, 255)

CJK_PATH = "/usr/share/fonts/truetype/wqy/wqy-zenhei.ttc"
MONO_PATH = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
MONO_B = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"

_fc = {}
def cjk(size):
    k = ("c", size)
    if k not in _fc:
        _fc[k] = ImageFont.truetype(CJK_PATH, size, index=0)
    return _fc[k]

def mono(size, bold=False):
    k = ("m", size, bold)
    if k not in _fc:
        _fc[k] = ImageFont.truetype(MONO_B if bold else MONO_PATH, size)
    return _fc[k]

def new_page():
    img = Image.new("RGB", (W, H), WHITE)
    return img, ImageDraw.Draw(img)

def text(d, xy, s, font, fill=INK, anchor="la"):
    d.text(xy, s, font=font, fill=fill, anchor=anchor)

def tw(d, s, font):
    return d.textlength(s, font=font)

def banner(d, x, y, w, s, size=30, pad=14):
    """dark blue banner with white text; returns bottom y"""
    f = cjk(size)
    bh = size + pad * 2
    d.rounded_rectangle([x, y, x + w, y + bh], radius=8, fill=DARK)
    text(d, (x + 18, y + bh / 2), s, f, WHITE, anchor="lm")
    return y + bh

def wrap(d, s, font, maxw):
    """wrap CJK/mixed text by char into lines fitting maxw"""
    lines = []
    cur = ""
    for ch in s:
        if ch == "\n":
            lines.append(cur); cur = ""
            continue
        if tw(d, cur + ch, font) > maxw and cur:
            lines.append(cur); cur = ch
        else:
            cur += ch
    if cur:
        lines.append(cur)
    return lines

def para(d, x, y, s, font, maxw, lh=None, fill=INK):
    if lh is None:
        lh = int(font.size * 1.5)
    for ln in wrap(d, s, font, maxw):
        text(d, (x, y), ln, font, fill)
        y += lh
    return y

def boxed(d, x, y, w, s, font, bg, br, padx=18, pady=14):
    lines = wrap(d, s, font, w - padx * 2)
    lh = int(font.size * 1.5)
    bh = len(lines) * lh + pady * 2
    d.rounded_rectangle([x, y, x + w, y + bh], radius=8, fill=bg)
    d.rectangle([x, y, x + 6, y + bh], fill=br)
    yy = y + pady
    for ln in lines:
        text(d, (x + padx, yy), ln, font, INK)
        yy += lh
    return y + bh

